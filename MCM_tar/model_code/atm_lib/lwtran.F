      subroutine lwtran(tj, rj, psj)
c
c  compute longwave atmospheric transmission coefficients
c
c ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
c
c  routine :   lwtran
c  called by : lwcool
c  calls :     lwco2
c  purpose :   compute longwave atmospheric transmission coefficients
c
c  inputs:
c     **passed** tj             celsius temperature at each grid point
c                                  (not used -- tdegk used instead)
c     **passed** rj             mixing ratio of h2o at each grid point
c     **passed** psj            surface presure at each ground point
c     / maim   / r              mixing ratios for h2o, co2, and o3
c                                  (code only uses o3 values)
c     / sigwgt / q, qmh, dq     "sigma" (pressure/po) terms
c  inputs computed in lwcool before it calls lwtran:
c     / planck / tdegk          temperature (kelvin)
c     / planck / pbb            blackbody function (total radiance)
c
c  outputs:
c     / trans /  transm         longwave transmission coefficient
c     / trans /  transz         correction to above for top level
c     / trans /  absrbx         quarter-level absorption
c
c
c  procedure:
c     the main purpose of this routine is to compute the band-integrated
c     transmission coefficients transm(i,k,l) for radiation passing from
c     flux level l to flux level k.  in addition, it computes two
c     corrections. the first, transz(i,k), is for radiation from the top
c     level (split off from transm to improve code efficiency, i think).
c     the second, absrbx(i,k,kq), is a half-layer (flux level to data-
c     input level, or vice versa) absorption correction; kq=1 is the
c     correction for upward flux and kq=2 is for downward flux.
c
c     this routine splits the longwave radiation spectrum into nb bands,
c     ranging from about 20 to 2000 cm-1.  transmission coefficients are
c     computed for each absorber contributing to absorption in that
c     band.  the single-absorber transmission coefficients are
c     multiplied together to produce the total single-band transmission,
c     and then subtracted from 1 to produce an absorption.  the single-
c     band absorptions are weighted by the relative fraction of
c     blackbody radiation in that band (for a particular temperature),
c     and summed to produce the total band-integrated absorption
c     coefficient, which is converted back to a transmission.
c
c     transmissions for h2o are computed using a goody random model.
c     the function form and coefficients come from a paper by rogers and
c     walshaw (rogers, c.d. and c.d. walshaw, the computation of infra-
c     red cooling in planetary atmospheres, quart. j. royal meteorol.
c     soc., v.92, pp.67-92, 1966).
c
c        the water vapor continuum is now computed by using the
c     formulation given in roberts(first fit). reference:
c     roberts,r.e.,et al,applied optics,v. 15,pp 2085-2090,1976.
c
c     the co2 transmission table was generated by a program obtained
c     privately from s.r. drayson, university of michigan.  this program
c     assumed a homogeneous path between flux levels; a version which
c     did not assume homogeneous paths was later published by drayson
c     (drayson, s.r., atmospheric transmission in the co2 bands between
c     12 microns and 18 microns, appl. opt., v.5, pp.385-391, 1973).
c
c     the o3 transmission computation, changed from a table lookup in
c     the original longwave radiation code, also uses a goody random
c     model.  the functional form and coefficients were published by
c     rogers (rogers, c.d., some extensions and applications of the new
c     random model for molecular band transmission, q.j.r.m.s, v.94,
c     pp.99-102, 1968).
c
c ++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++++
c
#include "parm.h"
#include "parmkp.h"
#include "parmrad.h"
      parameter ( sigma = 5.673e-5, c1 = 3.740e-5, c2 = 1.4385 )
      parameter ( po = 1013.25e3, opo = 1.0 / po, o2po = 0.5 * opo )
cc    parameter ( opo = 9.8692271e-7, o2po = 4.9346136e-7 )
      parameter ( ak1 = 223.0, ak2=10.0 )
c     parameter ( alpha = 0.28 )
c     parameter ( pi = 3.1415926535898 )
c     parameter ( pialph = pi * alpha )
      parameter ( ak1x4 = 4.0 * ak1 )
      parameter ( ak2x4 = 4.0 * ak2 )
cc    parameter ( pialph = 0.8796459, ak1x4 = 892.0, ak2x4 = 40.0 )
      parameter (            azint = 1.66                 )
cc    parameter ( g = 980.6, azint = 1.66, g1 = azint / g )
cc    parameter ( g1h = 0.5 * g1 )
cc    parameter ( g1 = 1.6938774e-3, g1h = 0.5 * g1 )
      parameter ( c3 = 1.0 / 120.0, a1 = 75.48, a2 = 23.44 )
cc    parameter ( c3 = 8.333333e-3, a1 = 75.48, a2 = 23.44 )
      parameter ( c3a1 = c3 * a1, c3a2 = c3 * a2 )
      parameter ( c0e = 9.999999810120017e-1 )
      parameter ( c1e = 9.999999599140620e-1/16.**1 )
      parameter ( c2e = 5.000056658124412e-1/16.**2 )
      parameter ( c3e = 1.666837874572320e-1/16.**3 )
      parameter ( c4e = 4.146341773620255e-2/16.**4 )
      parameter ( c5e = 7.279860860195404e-3/16.**5 )
c
#include "ctlblk.h"
c
#include "grid.h"
c
#include "h2olw.h"
c
#include "maimc.h"
c
#include "param.h"
c
#include "planck.h"
c
#include "sgwgt1.h"
c
#include "trans.h"
c
      dimension bw(ix,0:kx,nb), bwz(ix,nb), expzs(ix,nb)
      dimension trans(ix,0:kx,0:kx), dbbdt(ix,0:kx)
c
      dimension tj(ix,kx,nhem), rj(ix,kx,nhem), psj(ix,nhem)
c
      dimension vcube(nb), expz1(nb), c(nb), v(nb), dv(nb)
      dimension pdi   (ix,0:kp), pfl   (ix,0:kx), dpdi (ix,  kx)
      dimension rh2o  (ix,0:kp), ro3   (ix,0:kp), qdi  (ix,  kx)
      dimension duh2o (ix,  kx), duco2 (ix,  kx), duo3 (ix,  kx)
      dimension duqh2o(ix,  kx), duqfac(ix,  kx), dufac(ix,  kx)
      dimension fbignl(ix,  kx), bignel(ix,0:kx), bign (ix,  kx)
      dimension tdpfac(ix,  kx), tfac  (ix,  kx), teff (ix,  kx)
      dimension sfac  (ix,0:kx), pfac  (ix,0:kx), peff (ix,0:kx)
      dimension tcof  (ix,0:kx), fac1  (ix,0:kx), fac2 (ix,0:kx)
      dimension t260  (ix,0:kx), tadj  (ix,0:kx,2)
      dimension ulog  (ix,0:kx), plog  (ix,0:kx)
c
c  quarter-layer variables
c
      dimension txdegk(ix,0:kx), qx    (ix,0:kx), dpfac(ix,0:kx)
      dimension duxh2o(ix,0:kx), duxco2(ix,0:kx), duxo3(ix,0:kx)
c
      equivalence (ulog,  fac1  ), (plog,  fac2 ), (teff, peff )
      equivalence (txdegk,dpdi  ), (qx,    qdi  )
      equivalence (duxh2o,duh2o ), (duxco2,duco2), (duxo3,duo3 )
      equivalence (tadj,  duqfac), (tadj(1,0,2),dufac,tdpfac,dpfac)
c
c  constants for h2o bignell continuum absorption
c
c        these are the roberts continuum coefficients
      data  c / 4*0.0, 149.566, 38.103, 11.312, 7.9193, 6.0741, 4.9179,
     $          9*0.0 /
c
c  longwave frequency bands and band widths (inverse cm)
c
      data v /   20.0,  100.0,  220.0,  340.0,  470.0,
     $          670.0,  850.0,  930.0, 1020.0, 1140.0,
     $         1275.0, 1400.0, 1500.0, 1600.0, 1700.0,
     $         1800.0, 1900.0, 2000.0, 2125.0 /
      data dv /  40.0, 120.0, 120.0, 120.0, 140.0,
     $          260.0, 100.0,  60.0, 120.0, 120.0,
     $          150.0, 100.0, 100.0, 100.0, 100.0,
     $          100.0, 100.0, 100.0, 150.0 /
c
c ----------------------------------------------------------------------
c  description of variables and constants used in lwtran
c ----------------------------------------------------------------------
c
c  variables centered on data input levels:
c     q, dq                   1-d "sigma" (pressure/po) and d(sigma)/dk
c                             (not to be confused with planck bb sigma)
c     pdi, dpdi, qdi          pressure, d(pdi)/dk, and pdi/po
c     rh2o, rco2, ro3         mixing ratios for the various absorbers
c     duh2o, duco2, duo3      absorber amounts from top of atmosphere
c        (gm/cm**2)           (also called unadjusted optical depth)
c     tdegk                   temperature (kelvin)
c
c  variables centered on flux levels (see last paragraph, below):
c     qmh, pfl                1-d "sigma", 2-d pressure
c
c  assorted additional variables and constants:
c     po, opo, o2po           average pressure at sea level, 1/po, 2/po
c     pbb, dbbdt              planck blackbody function and d(pbb)/dt
c     sigma, c1, c2           constants in planck blackbody equation
c     v, dv                   frequencies and band widths (1/cm)
c                             (wavelength range is 5-500 microns)
c     bw, bwz                 weights for freq. bands derived from pbb
c     alpha, c3, a1, a2,      empirical constants used in computing
c       ak1, ak2                ozone absorption
c     aod, sod                empirical band constants for water lines
c       aod                     coefficient for h2o line width
c       sod                     coefficient for h2o line strength
c     sfac, pfac, tfac        intensity, pressure, temperature factors
c     peff, teff              effective pressure, temperature
c     ulog, plog              logs of co2 amount, effective pressure
c     tadj                    temperature adjustments for h2o lines
c     fbignl, bignel, bign    factors associated with bignell continuum
c     tcof                    transmission coefficient, single absorber
c     trans                   transmission matrix, single frequency band
c
c  output variables:
c     transm, transz          band-integrated transmission coefficients
c     absrbx                  quarter-layer correction to above (absrp.)
c
c  quarter layer variables (x usually indicates quarter-layer):
c     txdegk, qx              quarter-layer temperature, "sigma"
c     duxh2o, duxco2, duxo3   quarter-layer absorber amounts
c
c  miscellaneous constants:
c     azint                   azimuthal integral factor for diffuse rad.
c     g1, g1h                 convert dp*mix-ratio to absorber amount
c
c  miscellaneous temporaries:
c     expzs, tcube, vcube, bc, bandc1, bandc2
c     t260, fac1, fac2, dufac, dpfac, duqfac, duqh2o, cco2
c
c     vertical levels in the model are numbered from the top of the
c  atmosphere to the bottom; thus vertical level 1 is in the
c  stratosphere and level kx is just above the ground.  in the
c  radiation code, additional "pseudo-levels" are tacked onto the top
c  (level 0) and the bottom (level kp).  these levels make it easier
c  to handle incoming solar radiation and longwave radiation emanating
c  from the ground.
c
c     an additional complication to the level numbering system for the
c  radiation code is the use of "flux" levels and "data-input" levels.
c  the simplest numbering scheme for radiation calculations focuses
c  on even and odd levels: the grid variables (pressure, temperature,
c  etc.) reside at even levels, and flux is computed across them, i.e.,
c  from odd level to odd level.  this a pedagogically sound approach,
c  but it poses problems for computers, particularly vector types.
c  thus this code numbers what would be odd and even levels separately.
c  "data-input" levels are normal model vertical levels; "flux" levels
c  are halfway between them.  flux level k is one-half level closer to
c  the ground than data-input level k.  in the diagram below, data-input
c  levels are shown as "++++++" and flux levels are shown as "------".
c
c           description          level  index
c    incoming solar radiation      0      0   +++++++
c                                 1/2     0   -------
c             top model level      1      1   +++++++
c                                  .
c                                  .
c                                  .
c          bottom model level     kx     kx   +++++++
c                               kx+1/2   kx   -------
c                ground level     kp     kp   +++++++
c
c ----------------------------------------------------------------------
c  statement function
c ----------------------------------------------------------------------
c
c  the approximation to exp(x) which follows is appropriate only given
c  the following assumptions:
c    1) since the correction coefficients (apa & bpb) are known only
c       to about four digits of accuracy, 6-7 digits of accuracy for
c       the approximation is ample.
c    2) the input range for x is [-6.735,2.289].  this depends on:
c       a) the valid temperature range, now [-173.16,102] (celsius)
c       b) the values of the coefficients apa & bpb
c
      expx(x) = ((( (((((c5e*x+c4e)*x+c3e)*x+c2e)*x+c1e)*x+c0e)
     $             **2)**2)**2)**2
c
c ----------------------------------------------------------------------
c  Compute various constants involving gravity.
c ----------------------------------------------------------------------
      g1  = azint / grav
      g1h = 0.5 * g1
c ----------------------------------------------------------------------
c  compute band weights
c ----------------------------------------------------------------------
c
      do 50 lb=1,nb
        vcube(lb) = v(lb) * v(lb) ** 2
   50 continue
c
      do 52 lb=1,nb
        do 52 i=1,ix
          expzs(i,lb) = exp(c2 / tdegk(i,0) * v(lb)) - 1.0
   52 continue
c
      do 54 lb=1,nb
        bc = c1 * vcube(lb) * dv(lb)
        do 54 i=1,ix
          bwz(i,lb) = bc / (expzs(i,lb) * pbb(i,0))
   54 continue
c
      do 56 k=0,kx
        do 56 i=1,ix
          dbbdt(i,k) = 4.0 * sigma * tcube(i,k)
   56 continue
c
      do 58 lb=1,nb
        bandc1 = c1 * vcube(lb)
        bandc2 = c2 * v(lb)
        bc     = bandc1 * bandc2 * dv(lb)
        do 58 k=0,kx
          do 58 i=1,ix
            bw(i,k,lb) = exp(bandc2 / tdegk(i,k))
            bw(i,k,lb) = bc * bw(i,k,lb)
     $                   / ((bw(i,k,lb) - 1.0) * tdegk(i,k))**2
            bw(i,k,lb) = bw(i,k,lb) / dbbdt(i,k)
   58 continue
c
c ----------------------------------------------------------------------
c  compute field arrays needed for trans calculation
c    (note that tdegk has already been computed and stored in flux)
c ----------------------------------------------------------------------
c
      do 70 i=1,ix
        pdi(i, 0) = 0.0
        pfl(i, 0) = 0.0
        pdi(i,kp) = psj(i,ih)
   70 continue
c
      do 72 k=1,kx
        do 72 i=1,ix
          pdi (i,k) = psj(i,ih) * q(k)
          pfl (i,k) = psj(i,ih) * qmh(k)
          dpdi(i,k) = psj(i,ih) * dq(k)
          ro3 (i,k) = r(k,3)
   72 continue
c
      do 74 k=1,kx
        do 74 i=1,ix
          rh2o  (i,k) = rj(i,k,ih)
          qdi   (i,k) = (pfl(i,k) + pfl(i,k-1)) * o2po
          t260  (i,k) = tdegk(i,k) - 260.0
          fbignl(i,k) = exp(1800.0/tdegk(i,k)-6.081081081)
c        the kernel is      1800.0*(1.0/temp-1.0/296.0)
   74 continue
c
      do 76 i=1,ix
        rh2o(i, 0) = 0.0
        ro3 (i, 0) = 0.0
        rh2o(i,kp) = rh2o(i,kx)
        ro3 (i,kp) = ro3 (i,kx)
   76 continue
c
      do 77 k=1,kp
       do 77 i=1,ix
         rh2o(i,k) = max(rh2o(i,k),3.0e-6)
   77 continue
c
      cco2 = rco2 * g1
      do 78 k=1,kx
        do 78 i=1,ix
          duh2o (i,k) = dpdi  (i,k) * rh2o  (i,k) * g1
          duco2 (i,k) = dpdi  (i,k) * cco2
          duo3  (i,k) = dpdi  (i,k) * ro3   (i,k) * g1
          duqh2o(i,k) = duh2o (i,k) * qdi   (i,k)
          bignel(i,k) = (fbignl(i,k)*duqh2o(i,k)*rh2o(i,k))
     $                / (0.622+rh2o(i,k))
   78 continue
c
c ----------------------------------------------------------------------
c  compute transm and transz
c
c  transm(i,k,l) is the transmission coefficient for longwave radiation
c    passing from vertical level l to level k
c  transz is a correction for radiation from the top of the atmosphere
c ----------------------------------------------------------------------
c
      do 80 l=0,kx
       do 80 k=0,kx
        do 80 i=1,ix
         trans (i,k,l) = 0.0
         transm(i,k,l) = 0.0
   80 continue
      do 82 k=0,kx
       do 82 i=1,ix
        transz(i,k) = 0.0
   82 continue
c
c  ***** begin loop on longwave frequency bands *****
c
      do 2890 lb= 1, nb
c
c ****** h2o contribution
c
c ******  compute temperature adjustment to line strength and line width
c
        do 1300 l=1,2
          do 1300 k=1,kx
            do 1300 i=1,ix
              tadj(i,k,l) = (apa(lb,l) + bpb(lb,l) * t260(i,k))
     $                      * t260(i,k)
              tadj(i,k,l) = expx(tadj(i,k,l))
 1300   continue
c
        do 1310 k=0,kx
         do 1310 i=1,ix
          sfac(i,k) = 0.0
          pfac(i,k) = 0.0
 1310   continue
        do 1320 k=1,kx
         do 1320 i=1,ix
          bign(i,k) = 0.0
 1320   continue
c
c     compute h2o contribution to lower triangular half of trans matrix
c     note that a non-physical factor of sod has been folded into duqfac
c     to cancel the factor that arises when sfac is squared in 1550 loop
c
        asodsq = sod(lb) * aod(lb)
        if (sod(lb) .eq. 0.0) asodsq = aod(lb)
        do 1400 k=1,kx
          do 1400 i=1,ix
            dufac (i,k) = sod(lb) * duh2o (i,k) * tadj(i,k,2)
            duqfac(i,k) = asodsq  * duqh2o(i,k) * tadj(i,k,1)
 1400   continue
c
        do 1550 l=kx-1,0,-1
          do 1500 k=l+1,kx
            do 1500 i=1,ix
              sfac(i,k) = sfac(i,k) + dufac (i,l+1)
              pfac(i,k) = pfac(i,k) + duqfac(i,l+1)
              bign(i,k) = bign(i,k) + bignel(i,l+1)
 1500     continue
c
          do 1550 k=l+1,kx
            do 1550 i=1,ix
              trans(i,k,l) = exp(-c(lb) * bign(i,k)
     $                       - sfac(i,k) / sqrt(1.0 + sfac(i,k)**2
     $                         / pfac(i,k)))
 1550   continue
c
c ****** compute h2o contribution to diagonal elements of trans matrix
c
        diag = exp(-c(lb) - sod(lb) / sqrt(1.0 + sod(lb) / aod(lb)))
c
c ****** co2 contribution
c
        if (lb .ne. 6) goto 2500
c
        do 2005 k=0,kx
         do 2005 i=1,ix
          sfac(i,k) = 0.0
          pfac(i,k) = 0.0
 2005   continue
        do 2007 k=1,kx
         do 2007 i=1,ix
          tfac(i,k) = 0.0
 2007   continue
c
c **** compute co2 contribution to lower triangular half of trans matrix
c
        do 2010 k=1,kx
          do 2010 i=1,ix
            duqfac(i,k) = duco2(i,k) * qdi (i,k)
            tdpfac(i,k) = tdegk(i,k) * dpdi(i,k)
 2010   continue
c
        do 2050 l=kx-1,0,-1
          do 2020 k=l+1,kx
            do 2020 i=1,ix
              sfac(i,k) = sfac(i,k) + duco2 (i,l+1)
              pfac(i,k) = pfac(i,k) + duqfac(i,l+1)
              tfac(i,k) = tfac(i,k) + tdpfac(i,l+1)
              teff(i,k) = tfac(i,k) / (pfl(i,k) - pfl(i,l))
 2020     continue
          do 2030 k=l+1,kx
            do 2030 i=1,ix
              ulog(i,k) = alog10(sfac(i,k))
              plog(i,k) = alog10(pfac(i,k)) - ulog(i,k)
              ulog(i,k) = ulog(i,k) + 2.70668
 2030     continue
c
          if (l .eq. kx-1) then
            i = 0
            ulog(i,kx) = 2.70668
            plog(i,kx) = 0.0
            teff(i,kx) = 0.0
            len = ix + 1
          else
            i = 1
            len = ix * (kx - l)
          endif
c
c ****** call lwco2 to compute tcof values
c
          call lwco2(tcof(i,l+1), ulog(i,l+1),
     $               plog(i,l+1), teff(i,l+1), len)
c
c ****** compute co2 contribution to diagonal elements of trans matrix
c
          if (l .eq. kx-1) diag = tcof(i,kx) * diag
c
c ****** accumulate co2 tcof into trans (lower triangular half)
c
          do 2040 k=l+1,kx
            do 2040 i=1,ix
              trans(i,k,l) = tcof(i,k) * trans(i,k,l)
 2040     continue
 2050   continue
c
c ****** ozone contribution
c
 2500   if (lb .ne. 9) go to 2855
c
        do 2555 k=0,kx
         do 2555 i=1,ix
          sfac(i,k) = 0.0
          pfac(i,k) = 0.0
 2555   continue
c       sfac = 0.0
c       pfac = 0.0
c
c **** compute o3 contribution to lower triangular half of trans matrix
c
        do 2600 k=1,kx
          do 2600 i=1,ix
            duqfac(i,k) = pialph * duo3(i,k) * qdi(i,k)
 2600   continue
c
        do 2700 l=kx-1,0,-1
          do 2650 k=l+1,kx
            do 2650 i=1,ix
              sfac(i,k) = sfac(i,k) + duo3  (i,l+1)
              pfac(i,k) = pfac(i,k) + duqfac(i,l+1)
 2650     continue
          do 2700 k=l+1,kx
            do 2700 i=1,ix
              peff (i,k  ) = pfac(i,k) / sfac(i,k)
              fac1 (i,k  ) = sfac(i,k) / peff(i,k)
              fac2 (i,k  ) = 1.0 - exp(-5.0 * peff(i,k)
     $                              * (sqrt(1.0 + ak2x4 * fac1(i,k))
     $                                 - 1.0))
              fac1 (i,k  ) = 1.0 - exp(-5.0 * peff(i,k)
     $                              * (sqrt(1.0 + ak1x4 * fac1(i,k))
     $                                 - 1.0))
              tcof (i,k  ) = 1.0
     $                       - (c3a1 * fac1(i,k) + c3a2 * fac2(i,k))
              trans(i,k,l) = tcof(i,k) * trans(i,k,l)
 2700   continue
c
c ****** compute o3 contribution to diagonal elements of trans matrix
c
        factr1 = 1.0 - exp(-5.0 * pialph
     $                     * (sqrt(1.0 + ak1x4 / pialph) - 1.0))
        factr2 = 1.0 - exp(-5.0 * pialph
     $                     * (sqrt(1.0 + ak2x4 / pialph) - 1.0))
        diago3 = 1.0 - (c3a1 * factr1 + c3a2 * factr2)
        diag   = diago3 * diag
c
c ****** apply band weights to trans; accumulate
c ****** as absorp. in transm & transz
c
c ****** first convert trans and diag to absorption
c
 2855   continue
        do 2857 l=0,kx
         do 2857 k=0,kx
          do 2857 i=1,ix
           trans(i,k,l) = 1.0 - trans(i,k,l)
 2857   continue
        diag  = 1.0 - diag
c
        do 2860 l=0,kx-1
          do 2860 k=l+1,kx
            do 2860 i=1,ix
              transm(i,k,l) = transm(i,k,l) + trans(i,k,l) * bw(i,l,lb)
 2860   continue
c
        do 2865 l=1,kx
          do 2865 k=0,l-1
            do 2865 i=1,ix
              transm(i,k,l) = transm(i,k,l) + trans(i,l,k) * bw(i,l,lb)
 2865   continue
c
        do 2870 l=0,kx
          do 2870 i=1,ix
            transm(i,l,l) = transm(i,l,l) + diag * bw(i,l,lb)
 2870   continue
c
        do 2875 l=1,kx
          do 2875 i=1,ix
            transz(i,l) = transz(i,l) + trans(i,l,0) * bwz(i,lb)
 2875   continue
c
        do 2880 i=1,ix
          transz(i,0) = transz(i,0) + diag * bwz(i,lb)
 2880   continue
c
 2890 continue
c
c  ***** end loop on longwave frequency bands *****
c
c  convert transm & transz from absorption to transmission coefficients
c
      do 2897 l=0,kx
       do 2897 k=0,kx
        do 2897 i=1,ix
         transm(i,k,l) = 1.0 - transm(i,k,l)
 2897 continue
       do 2898 k=0,kx
        do 2898 i=1,ix
         transz(i,k) = 1.0 - transz(i,k)
 2898 continue
c
c ----------------------------------------------------------------------
c  compute absrbx
c
c  absrbx is a correction for the finite thickness of the vertical
c    levels, and represents within-layer absorption of radiation
c ----------------------------------------------------------------------
c
c     absrbx = 0.0
      do 2899 l=1,2
       do 2899 k=0,kx
        do 2899 i=1,ix
         absrbx(i,k,l) = 0.0
 2899 continue
c
c  kq=1 is the upward-flux correction; kq=2 is for downward flux
c
      do 5000 kq=1,2
c
c  compute coefficients needed for quarter-layer correction
c
        if (kq.eq.2) goto 3050
c
        do 3010 k=1,kx-1
          do 3010 i=1,ix
            dpfac(i,k) = (pdi(i,k+1) - pfl(i,k)) * g1h
 3010   continue
c
        do 3020 k=1,kx-1
          do 3020 i=1,ix
            txdegk(i,k) = 0.375 * tdegk(i,k) + 0.625 * tdegk(i,k+1)
            qx    (i,k) = (0.75 * pfl(i,k) + 0.25 * pdi(i,k+1)) * opo
            duxh2o(i,k) = (0.375 * rh2o(i,k) + 0.625 * rh2o(i,k+1))
     $                    * dpfac(i,k)
            duxco2(i,k) = rco2 * dpfac(i,k)
            duxo3 (i,k) = (0.375 * ro3(i,k) + 0.625 * ro3(i,k+1))
     $                    * dpfac(i,k)
            bignel(i,k) = (0.375 * rh2o(i,k) + 0.625 * rh2o(i,k+1))**2
     $                    * dpfac(i,k) * fbignl(i,k+1) /
     $                    (0.622 + 0.375*rh2o(i,k) + 0.625*rh2o(i,k+1))
 3020   continue
c
        do 3030 i=1,ix
          txdegk(i, 0) = 0.75 * tdegk(i,0) + 0.25 * tdegk(i,1)
          txdegk(i,kx) = tdegk(i,kp)
          qx    (i, 0) = (0.75 * pdi(i,0) + 0.25 * pdi(i,1)) * opo
          qx    (i,kx) = psj(i,ih) * opo
          duxh2o(i, 0) = (0.25 * rh2o(i,0) + 0.75 * rh2o(i,1))
     $                    * (pdi(i,1) - pdi(i,0)) * g1h
          duxh2o(i,kx) = 0.0
          duxco2(i, 0) = rco2 * (pdi(i,1) - pdi(i,0)) * g1h
          duxco2(i,kx) = 0.0
          duxo3 (i, 0) = (0.25 * ro3(i,0) + 0.75 * ro3(i,1))
     $                   * (pdi(i,1) - pdi(i,0)) * g1h
          duxo3 (i,kx) = 0.0
          bignel(i, 0) = (0.75 * rh2o(i,0) + 0.25 * rh2o(i,1))**2
     $                 * (pdi(i,1)-pdi(i,0)) * g1h * fbignl(i,1) /
     $                   (0.622 + 0.75*rh2o(i,0) + 0.25*rh2o(i,1))
          bignel(i,kx) = 0.0
 3030   continue
c
        do 3040 k=0,kx
          do 3040 i=1,ix
            t260(i,k) = txdegk(i,k) - 260.0
 3040   continue
c
        go to 3100
c
 3050   do 3060 k=1,kx-1
          do 3060 i=1,ix
            dpfac(i,k) = (pfl(i,k) - pdi(i,k)) * g1h
 3060   continue
c
        do 3070 k=1,kx-1
          do 3070 i=1,ix
            txdegk(i,k) = 0.625 * tdegk(i,k) + 0.375 * tdegk(i,k+1)
            qx    (i,k) = (0.75 * pfl(i,k) + 0.25 * pdi(i,k)) * opo
            duxh2o(i,k) = (0.625 * rh2o(i,k) + 0.375 * rh2o(i,k+1))
     $                    * dpfac(i,k)
            duxco2(i,k) = rco2 * dpfac(i,k)
            duxo3 (i,k) = (0.625 * ro3(i,k) + 0.375 * ro3(i,k+1))
     $                    * dpfac(i,k)
            bignel(i,k) = (0.625*rh2o(i,k) + 0.375*rh2o(i,k+1))**2
     *                    * dpfac(i,k) * fbignl(i,k) /
     *                    (0.622 + 0.625*rh2o(i,k) + 0.375*rh2o(i,k+1))
 3070   continue
c
        do 3080 i=1,ix
          txdegk(i, 0) = tdegk(i,0)
          txdegk(i,kx) = 0.75 * tdegk(i,kp) + 0.25 * tdegk(i,kx)
          qx    (i, 0) = 1.0
          qx    (i,kx) = (0.75 * pdi(i,kp) + 0.25 * pdi(i,kx)) * opo
          duxh2o(i, 0) = 0.0
          duxh2o(i,kx) = (0.75 * rh2o(i,kp) + 0.25 * rh2o(i,kx))
     $                   * (pdi(i,kp) - pdi(i,kx)) * g1h
          duxco2(i, 0) = 0.0
          duxco2(i,kx) = rco2 * (pdi(i,kp) - pdi(i,kx)) * g1h
          duxo3 (i, 0) = 0.0
          duxo3 (i,kx) = (0.75 * ro3(i,kp) + 0.25 * ro3(i,kx))
     $                   * (pdi(i,kp) - pdi(i,kx)) * g1h
          bignel(i, 0) = 0.
          bignel(i,kx) = (0.75 * rh2o(i,kp) + 0.25 * rh2o(i,kx))**2
     *                 * (pdi(i,kp)-pdi(i,kx)) * g1h * fbignl(i,kx) /
     *                   (0.622 + 0.75*rh2o(i,kp) + 0.25*rh2o(i,kx))
 3080   continue
c
        do 3090 k=0,kx
          do 3090 i=1,ix
            t260(i,k) = txdegk(i,k) - 260.0
 3090   continue
c
c  ***** begin loop on longwave frequency bands *****
c
 3100   do 4000 lb=1,nb
c
c ****** quarter-layer h2o absorption
c
c ****** compute temperature adjustment to line strength and line width
c
          do 3150 k=0,kx
            do 3150 i=1,ix
              tadj(i,k,1) = (apa(lb,1) + bpb(lb,1) * t260(i,k))
     $                      * t260(i,k)
              tadj(i,k,2) = (apa(lb,2) + bpb(lb,2) * t260(i,k))
     $                      * t260(i,k)
              tadj(i,k,1) = tadj(i,k,1) - tadj(i,k,2)
 3150     continue
c
          do 3200 l=1,2
            do 3200 k=0,kx
              do 3200 i=1,ix
                tadj(i,k,l) = expx(tadj(i,k,l))
 3200     continue
c
c ****** compute h2o contribution to quarter-layer absorption matrix
c
          do 3300 k=0,kx
            do 3300 i=1,ix
              sfac (i,k   ) = sod(lb) * duxh2o(i,k) * tadj(i,k,2)
              pfac (i,k   ) = aod(lb) * qx    (i,k) * tadj(i,k,1)
              trans(i,k,kq) = exp(-c(lb) * bignel(i,k)
     $                       -sfac(i,k)/sqrt(1.0+sfac(i,k)/pfac(i,k)))
 3300     continue
c
c ****** quarter-layer co2 absorption
c
          if (lb .ne. 6) go to 3700
c
c ****** compute co2 contribution to quarter-layer absorption matrix
c
          len = ix * kp
          do 3410 k=0,kx
           do 3410 i=1,ix
            sfac(i,k) = duxco2(i,k)
 3410     continue
          do 3420 k=0,kx
           do 3420 i=1,ix
            duxco2(i,k) = max(duxco2(i,k),1.0e-6)
 3420     continue
          do 3500 k=0,kx
            do 3500 i=1,ix
              ulog(i,k) = alog10(duxco2(i,k)) + 2.70668
              plog(i,k) = alog10(qx(i,k))
 3500     continue
c
c ****** call lwco2 to compute tcof values
c
          call lwco2(tcof(1,0),ulog(1,0),plog(1,0),txdegk(1,0),len)
c
c ****** accumulate co2 ccp into trans
c
          do 3600 k=0,kx
            do 3600 i=1,ix
              tcof(i,k) = tcof(i,k) * trans(i,k,kq)
 3600     continue
          do 3610 k=0,kx
           do 3610 i=1,ix
            if(sfac(i,k) .gt. 0.0) then
              trans(i,k,kq) = tcof(i,k)
            endif
 3610     continue
c
c ****** quarter-layer o3 absorption
c
 3700     if (lb .ne. 9) go to 3900
c
          do 3800 k=0,kx
            do 3800 i=1,ix
              peff (i,k   ) = pialph * qx(i,k)
              fac2 (i,k   ) = duxo3(i,k) / peff(i,k)
              fac1 (i,k   ) = 1.0
     $                        - exp(-5.0 * peff(i,k)
     $                              * (sqrt(1.0 + ak1x4 * fac2(i,k))
     $                                 - 1.0))
              fac2 (i,k   ) = 1.0
     $                        - exp(-5.0 * peff(i,k)
     $                              * (sqrt(1.0 + ak2x4 * fac2(i,k))
     $                                 - 1.0))
              tcof (i,k   ) = 1.0 - (c3a1 * fac1(i,k) + c3a2 *fac2(i,k))
              trans(i,k,kq) = tcof(i,k) * trans(i,k,kq)
 3800     continue
c
c ****** total quarter-layer absorption
c
 3900     do 4000 k=0,kx
            do 4000 i=1,ix
              absrbx(i,k,kq) = absrbx(i,k,kq)
     $                         + (1.0 - trans(i,k,kq)) * bw(i,k,lb)
 4000 continue
c
 5000 continue
c
c  ***** end of principal quarter-layer loop *****
c
      return
      end
