c     this routine performs a vectorized gaussian quadrature
c      accumulation. see january 27,1982 notes.
c
c     new harm(m,n,k) = cons * p(m,n) * (ft(m,k) + ft2(m,k) 
c                     + previous harm(m,n,k)
c        for n=1 to jtrun1, m=1 to mx, and k=1 to kmax
c        where harm and ftsum and ftdif are complex
c
c     ft represents either ftsum or ftdif depending on whether index n
c       is odd or even.
c     ft2 represents either ftsum or ftdif depending on whether index n
c       is odd or even.
c     ftsum are the sum fourier components contributing to the odd
c       n harmonic components.
c     ftdif are the difference fourier components contributing to the
c       even n harmonics.
c
#include "parm.h"
#include "parmjx.h"
#include "clnpol.h"
c
c
c     the jxth column of p is not zeroed since it is not
c     used in the quadature.
c
      dimension g(mx2,jx,1), h(mx2,jx,1)
      dimension  p1(mx2,jx),p2(mx2,jx)
      dimension fs1(mx2,1),fd1(mx2,1)
      dimension fs2(mx2,1),fd2(mx2,1)
c
c  below are statement functions to multiply the polyinomial to the
c   ftsum (ftdif)
c
      hs(i)=h(m,i,k)+p1(m,i)*(fs1(m,k)*cnst1)+p2(m,i)*(fs2(m,k)*cnst2)
      hd(i)=h(m,i,k)+p1(m,i)*(fd1(m,k)*cnst1)+p2(m,i)*(fd2(m,k)*cnst2)
c
c
      cnst1=float(jin)*cons1
      cnst2=float(jin)*cons2
c
      do 13 k=1,kmx
#ifdef r15
      do 1  m=1,mx2
      g(m, 1,k) = hs( 1)
      g(m, 3,k) = hs( 3)
      g(m, 5,k) = hs( 5)
      g(m, 7,k) = hs( 7)
      g(m, 9,k) = hs( 9)
      g(m,11,k) = hs(11)
      g(m,13,k) = hs(13)
      g(m,15,k) = hs(15)
c
      g(m, 2,k) = hd( 2)
      g(m, 4,k) = hd( 4)
      g(m, 6,k) = hd( 6)
      g(m, 8,k) = hd( 8)
