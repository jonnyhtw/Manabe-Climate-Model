      subroutine passup
c
#include "parm.h"
#include "parmkp.h"
      parameter ( maxit = 3 )
c
      dimension tab (223), est(223)
      dimension tab1(101)
      dimension tab2( 80)
      dimension tab3( 42)
      dimension psq(ix,kx), fadph(ix,kx)  , tkph(ix,kx)
      dimension es(ix,kx) , t7(ix,kx,nhem), ps7(ix,nhem)
c
#include "ctlblk.h"
c
#include "grid.h"
c
#include "param.h"
c
#include "sgwgt1.h"
c
      dimension tes(ix,kx),psqph(ix,kx),it(ix,kx)
c
      equivalence (est(  1),tab (1))
      equivalence (tab(  1),tab1(1))
      equivalence (tab(102),tab2(1))
      equivalence (tab(182),tab3(1))
      equivalence (psq  (1,1),gvor (1,1,1)), (fadph(1,1),gdiv  (1,1,1))
      equivalence (tkph (1,1),gucos(1,1,1)), (es   (1,1),gvcos (1,1,1))
      equivalence (t7 (1,1,1),cgt  (1,1,1)), (ps7(1,1),  gvbrps(1,1))
c
      data tab1 /21*0.01403,0.01719,0.02101,0.02561,0.03117,0.03784,
     *.04584,.05542,.06685,.08049,.09672,.1160,.1388,.1658,.1977,.2353,
     *.2796,.3316,.3925,.4638,.5472,.6444,.7577,.8894,1.042,1.220,1.425,
     *1.662,1.936,2.252,2.615,3.032,3.511,4.060,4.688,5.406,6.225,7.159,
     *8.223,9.432,10.80,12.36,14.13,16.12,18.38,20.92,23.80,27.03,30.67,
     *34.76,39.35,44.49,50.26,56.71,63.93,71.98,80.97,90.98,102.1,114.5,
     *128.3,143.6,160.6,179.4,200.2,223.3,248.8,276.9,307.9,342.1,379.8,
     *421.3,466.9,517.0,572.0,632.3,698.5,770.9,850.2,937.0,1032./
c
      data tab2               /1146.6,1272.0,1408.1,1556.7,1716.9,1890.3
     * ,2077.6,2279.6,2496.7,2729.8,2980.0,3247.8,3534.1,3839.8,4164.8,
     *4510.5,4876.9,5265.1,5675.2,6107.8,6566.2,7054.7,7575.3,8129.4,
     *8719.2,
     *     9346.5,10013.,10722.,11474.,12272.,13119.,14017.,14969.,
     *15977.,
     *   17044.,18173.,19367.,20630.,21964.,23373.,24861.,26430.,28086.
     *,29831.,31671.,33608.,35649.,37796.,40055.,42430.,44927.,47551.,
     *50307.,53200.,56236.,59422.,62762.,66264.,69934.,73777.,77802.,
     *82015.,
     *     86423.,91034.,95855.,100890.,106160.,111660.,117400.,123400.
     *,129650.,136170.,142980.,150070.,157460.,165160.,173180.,181530.,
     *190220.,199260./
c
      data tab3                /208670.,218450.,228610.,239180.,250160.,
     *261560.,273400.,285700.,298450.,311690.,325420.,339650.,354410.,
     *369710.,385560.,401980.,418980.,436590.,454810.,473670.,493170.,
     *513350.,534220.,555800.,578090.,601130.,624940.,649530.,674920.,
     *701130.,728190.,756110.,784920.,814630.,845280.,876880.,909450.,
     *943020.,977610.,1013250.,1049940.,1087740./
c
c   <> <> <> <> <> <> <> <> <> <> <> <> <> <> <> <> <> <> <> <> <> <> <>
c
c     moist adiabatic adjustment
c
      do 116 i=1,ix
        ps7(i,ih) = exp(gps(i,1))
  116 continue
c
      do 120 k=1,km
        do 120 i=1,ix
          psqph(i,k) = ps7(i,ih) * qmh (k)
          psq  (i,k) = ps7(i,ih) * dqph(k)
  120 continue
c
      do 135 iter=1,maxit
        do 130 k=1,km
          do 130 i=1,ix
            tkph(i,k) = 0.5 * (t7(i,k,ih) + t7(i,k+1,ih)) + tfra
            es(i,k)   = tkph(i,k) - 152.16
            it(i,k)   = max0(1, min1(222., es(i,k)))
  130   continue
        do 1301 k=1,km
          do 1301 i=1,ix
            tes  (i,k) = est(it(i,k)  )
            fadph(i,k) = est(it(i,k)+1)
 1301   continue
        do 1302 k=1,km
          do 1302 i=1,ix
            es(i,k)    = tes(i,k)
     *                 + (fadph(i,k) - tes(i,k)) * (es(i,k) - it(i,k))
            fadph(i,k) = cappa * psq(i,k)
     *                 * (tkph(i,k) + 5439.0 * es(i,k) / psqph(i,k))
     *                    / (psqph(i,k) + 6.38e6 * es(i,k)
     *                      / (tkph(i,k) - 35.7) ** 2)
 1302   continue
        do 135 k=1,km
          do 135 i=1,ix
            if (t7(i,kp-k,ih) - fadph(i,kx-k) .gt. t7(i,kx-k,ih)) then
              t7(i,kx-k,ih) = (dq(kp-k) * (t7(i,kp-k,ih)
     *                                     - fadph(i,kx-k))
     *                         + dq(kx-k)*t7(i,kx-k,ih))*dqi(kx-k)
              t7(i,kp-k,ih) = t7(i,kx-k,ih) + fadph(i,kx-k)
            endif
  135 continue
c
      return
      end
